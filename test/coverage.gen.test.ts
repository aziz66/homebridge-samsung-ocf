import { describe, it, expect } from "vitest";
import { readFileSync, readdirSync, writeFileSync, existsSync } from "node:fs";
import { join } from "node:path";
import { buildServices } from "../src/registry/engine";
import { parseDevice0Batch } from "../src/ocf/discovery";

const FIX = join(__dirname, "fixtures", "samsung");
const ORACLE = join(__dirname, "..", "research", "oracle", "oracle.json");

interface Row { name: string; archetype: string; resources: number; mapped: number; services: string[]; oracleEntities?: number; }

describe("coverage report", () => {
  it("builds services for every fixture and writes docs/COVERAGE.md", () => {
    const oracle = existsSync(ORACLE) ? JSON.parse(readFileSync(ORACLE, "utf8")).fixtures : {};
    const rows: Row[] = [];
    const unmappedBases: Record<string, number> = {};
    const serviceKinds: Record<string, number> = {};
    const names = readdirSync(FIX).filter((n) => n.endsWith("_device.json"));
    for (const f of names) {
      const name = f.replace("_device.json", "");
      const d = JSON.parse(readFileSync(join(FIX, f), "utf8"));
      const map = new Map(Object.entries(parseDevice0Batch(d.device0)));
      const r = buildServices(map, []);
      for (const s of r.services) serviceKinds[s.service] = (serviceKinds[s.service] ?? 0) + 1;
      for (const href of map.keys()) {
        if (!r.mappedHrefs.has(href)) {
          const base = href.split("/vs/")[0].replace(/\/\d+$/, "");
          unmappedBases[base] = (unmappedBases[base] ?? 0) + 1;
        }
      }
      rows.push({
        name, archetype: r.archetype, resources: map.size, mapped: r.mappedHrefs.size,
        services: r.services.map((s) => s.service),
        oracleEntities: oracle[name]?.num_bound_entities,
      });
    }

    // aggregate by archetype
    const byArch: Record<string, { n: number; res: number; mapped: number; svc: number }> = {};
    for (const row of rows) {
      const a = (byArch[row.archetype] ??= { n: 0, res: 0, mapped: 0, svc: 0 });
      a.n++; a.res += row.resources; a.mapped += row.mapped; a.svc += row.services.length;
    }

    const totalMapped = rows.reduce((s, r) => s + r.mapped, 0);
    const totalRes = rows.reduce((s, r) => s + r.resources, 0);
    const withPrimary = rows.filter((r) => r.services.length > 0).length;

    let md = "# HomeKit coverage (honest account)\n\n";
    md += "Generated by test/coverage.gen.test.ts over the " + rows.length + " captured fixtures.\n\n";
    md += "**What this measures.** This plugin maps the subset of each Samsung appliance's\n";
    md += "OCF resources that HomeKit can represent (temperature, humidity, power, doors,\n";
    md += "fan speed, filter life, climate). HomeKit has no generic select/enum, duration,\n";
    md += "or washer service, so capabilities like cycle/course selection, arbitrary mode\n";
    md += "enums, stateless buttons, time-of-day and free-form status strings have no HomeKit\n";
    md += "equivalent and are intentionally not exposed; some resources listed as unmapped\n";
    md += "below (lights, some switches, PM density) are representable and are future work. The\n";
    md += "reference localthings (Home Assistant) exposes far more because HA's entity\n";
    md += "model is richer. The 'localthings entities' column is that reference count,\n";
    md += "for context — it is NOT a target this plugin can reach on HomeKit.\n\n";
    md += "**Reads replay real captures. Writes are modelled, not hardware-verified.**\n\n";
    md += "## Totals\n\n";
    md += "- Fixtures: " + rows.length + "\n";
    md += "- Fixtures that produce at least one HomeKit service: " + withPrimary + "\n";
    md += "- OCF resources mapped to HomeKit: " + totalMapped + " of " + totalRes + " present (" + Math.round((100 * totalMapped) / totalRes) + "%)\n\n";
    md += "## HomeKit services produced (across all fixtures)\n\n| Service | Count |\n|---|---|\n";
    for (const [k, v] of Object.entries(serviceKinds).sort((a, b) => b[1] - a[1])) md += `| ${k} | ${v} |\n`;
    md += "\n## By appliance archetype\n\n| Archetype | Fixtures | Avg OCF resources | Avg mapped | Avg HomeKit services |\n|---|---|---|---|---|\n";
    for (const [a, v] of Object.entries(byArch).sort((x, y) => y[1].n - x[1].n))
      md += `| ${a} | ${v.n} | ${Math.round(v.res / v.n)} | ${Math.round(v.mapped / v.n)} | ${(v.svc / v.n).toFixed(1)} |\n`;
    md += "\n## Most common OCF resources NOT mapped to HomeKit\n\n";
    md += "These are present on appliances but have no clean HomeKit representation\n(config, diagnostics, enums, stateless actions, vendor metadata).\n\n| Resource base | Fixtures | Why unmapped (typical) |\n|---|---|---|\n";
    const reason: Record<string, string> = {
      "/mode": "mode/enum select — no generic HomeKit characteristic",
      "/course": "wash course list — no HomeKit equivalent",
      "/alarms": "alarm list — no HomeKit equivalent",
      "/information": "model/serial metadata",
      "/otninformation": "firmware update metadata",
      "/configuration": "region/time config",
      "/energy/consumption": "energy metering — needs Eve custom characteristics (future)",
      "/drlc": "demand-response config",
      "/diagnosis": "diagnostics action",
      "/sec": "TV/soundbar vendor modes",
    };
    for (const [b, c] of Object.entries(unmappedBases).sort((a, z) => z[1] - a[1]).slice(0, 25))
      md += `| ${b} | ${c} | ${reason[b] ?? "vendor/config/stateless"} |\n`;
    md += "\n## Per-fixture detail\n\n| Fixture | Archetype | Resources | Mapped | HomeKit services | localthings entities (ref) |\n|---|---|---|---|---|---|\n";
    for (const r of rows.sort((a, b) => a.name.localeCompare(b.name)))
      md += `| ${r.name} | ${r.archetype} | ${r.resources} | ${r.mapped} | ${r.services.join(", ") || "—"} | ${r.oracleEntities ?? "?"} |\n`;

    // Fixtures the engine routed to no archetype (generic), and fixture files
    // the oracle/engine glob does not cover (non-_device.json captures).
    const unrouted = rows.filter((r) => r.archetype === "generic").map((r) => r.name);
    const allFixtureFiles = readdirSync(FIX).filter((n) => n.endsWith(".json") && n !== "NOTICE.md");
    const processed = new Set(names);
    const skipped = allFixtureFiles.filter((n) => n.endsWith(".json") && !n.endsWith("_device.json") && !n.endsWith(".md"));
    md += "\n## Fixtures routed to the generic archetype (no dedicated primary service)\n\n";
    md += unrouted.length ? unrouted.map((n) => "- " + n).join("\n") + "\n" : "(none)\n";
    md += "\n## Fixture files not processed (no \`_device.json\` suffix)\n\n";
    md += "These are alternate captures (e.g. 8888-family) the oracle glob skips; " +
      "listed so the corpus is fully accounted for.\n\n";
    md += skipped.length ? skipped.map((n) => "- " + n).join("\n") + "\n" : "(none)\n";
    void processed;
    writeFileSync(join(__dirname, "..", "docs", "COVERAGE.md"), md);
    expect(withPrimary).toBeGreaterThan(rows.length * 0.6);
    expect(totalMapped).toBeGreaterThan(0);
  });
});
